package com.moodflix.backend.model;

public class Trailer {
    private String key;
    private String type;
    private boolean official;
    private String site;

    public String getKey() {
        return key;
    }

    public String getType() {
        return type;
    }

    public boolean isOfficial() {
        return official;
    }

    public String getSite() {
        return site;
    }
}
